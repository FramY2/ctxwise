import { mkdir, readdir, readFile, stat, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { parse as parseYaml, stringify as stringifyYaml } from "yaml";
import { z } from "zod";

const presetSchema = z
  .object({
    name: z.string().min(1),
    stack: z.string().min(1),
    description: z.string().min(1),
    budget: z.object({
      maxKnownTokens: z.number().int().positive(),
      maxContributorTokens: z.number().int().positive(),
      unknown: z.enum(["warn", "fail"]).default("warn"),
    }),
    recommendedMcpServers: z.array(z.string()).default([]),
    rules: z.array(z.string()).min(1),
  })
  .strict();

export type CtxWisePreset = z.infer<typeof presetSchema>;

function defaultPresetsDirectory(): string {
  return resolve(dirname(fileURLToPath(import.meta.url)), "..", "presets");
}

async function exists(path: string): Promise<boolean> {
  try {
    await stat(path);
    return true;
  } catch {
    return false;
  }
}

export function parsePresetYaml(content: string): CtxWisePreset {
  return presetSchema.parse(parseYaml(content));
}

export async function listBuiltInPresets(
  presetsDir = defaultPresetsDirectory(),
): Promise<CtxWisePreset[]> {
  if (!(await exists(presetsDir))) return [];
  const entries = await readdir(presetsDir, { withFileTypes: true });
  const presets: CtxWisePreset[] = [];

  for (const entry of entries) {
    if (!entry.isFile() || !entry.name.endsWith(".yaml")) continue;
    const raw = await readFile(join(presetsDir, entry.name), "utf8");
    presets.push(parsePresetYaml(raw));
  }

  return presets.sort((a, b) => a.name.localeCompare(b.name));
}

export function renderPresetGuidanceMarkdown(preset: CtxWisePreset): string {
  const lines = [
    `# Project Agent Guidelines (${preset.stack})`,
    "",
    `> Generated by CtxWise preset \`${preset.name}\` · Token budget: <= ${preset.budget.maxKnownTokens} startup tokens`,
    "",
    "## Core Engineering Rules",
    ...preset.rules.map((rule) => `- ${rule}`),
  ];

  if (preset.recommendedMcpServers.length > 0) {
    lines.push(
      "",
      "## Recommended MCP Surface",
      ...preset.recommendedMcpServers.map((server) => `- \`${server}\``),
    );
  }

  return `${lines.join("\n")}\n`;
}

export async function applyPresetToProject(options: {
  presetName: string;
  projectRoot: string;
  presetsDir?: string;
  writeGuidance?: boolean;
}): Promise<{
  preset: CtxWisePreset;
  budgetPath: string;
  guidancePaths: string[];
}> {
  const presets = await listBuiltInPresets(options.presetsDir);
  const preset = presets.find((item) => item.name === options.presetName);
  if (!preset) {
    const available = presets.map((p) => p.name).join(", ") || "none";
    throw new Error(
      `Unknown preset "${options.presetName}". Available presets: ${available}`,
    );
  }

  const root = resolve(options.projectRoot);
  const budgetPath = join(root, "ctxwise.budget.yaml");
  const budgetYaml = stringifyYaml({
    version: 1,
    maxKnownTokens: preset.budget.maxKnownTokens,
    maxContributorTokens: preset.budget.maxContributorTokens,
    unknown: preset.budget.unknown,
  });

  await mkdir(root, { recursive: true });
  await writeFile(budgetPath, budgetYaml, "utf8");

  const guidancePaths: string[] = [];
  if (options.writeGuidance) {
    const markdown = renderPresetGuidanceMarkdown(preset);
    for (const fileName of ["AGENTS.md", "CLAUDE.md"]) {
      const target = join(root, fileName);
      await writeFile(target, markdown, "utf8");
      guidancePaths.push(target);
    }
  }

  return {
    preset,
    budgetPath,
    guidancePaths,
  };
}
